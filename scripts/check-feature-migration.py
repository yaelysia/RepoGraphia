"""Exercise actual file imports, plan/preview/confirm, partial migration and correction."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
p=argparse.ArgumentParser();p.add_argument('report');p.add_argument('--set-content',action='store_true');p.add_argument('--chromium');a=p.parse_args()
root=Path(a.report).resolve();passed=[];errors=[];requests=[]
def check(ok,name):
    assert ok,name
    passed.append(name)
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True,**({'executable_path':a.chromium} if a.chromium else {}))
    page=browser.new_page(viewport={'width':1650,'height':1100},accept_downloads=True)
    page.on('pageerror',lambda e:errors.append(str(e)));page.on('request',lambda r:requests.append(r.url));page.on('dialog',lambda d:d.accept())
    def load(name):
        if a.set_content:page.set_content((root/name).read_text(),wait_until='load')
        else:page.goto((root/name).as_uri())
        page.locator('#features-tab').click()
    load('migration-fixture.html')
    initial=json.loads(page.locator('#graph-data').text_content())
    check('4 条失效' in page.locator('#feature-summary').inner_text(),'old annotations initially stale')
    page.locator('#feature-migrate').click();check(page.locator('#feature-migration').is_visible(),'migration has explicit entry')
    page.locator('#migration-old-graph').set_input_files({'name':'wrong.json','mimeType':'application/json','buffer':b'{}'})
    expect(page.locator('#feature-notice')).to_contain_text('失败');check('4 条失效' in page.locator('#feature-summary').inner_text(),'invalid graph preserves sidecar')
    page.locator('#migration-old-graph').set_input_files(str(root/'migration-fixture-old.json'))
    expect(page.locator('.migration-row')).to_have_count(4)
    check('1 条可复用' in page.locator('#migration-summary').inner_text(),'real fixture categorizes exactly one reusable')
    check('2 条需审阅' in page.locator('#migration-summary').inner_text() and '1 条无匹配' in page.locator('#migration-summary').inner_text(),'changed and missing separated')
    check('已选择 0 条' in page.locator('#migration-summary').inner_text(),'default is defer, no hidden migration')
    page.screenshot(path=str(root/'preview-migration-plan.png'),full_page=True)
    page.locator('.migration-row[data-mapping="change"]').click()
    check(page.get_by_label('迁移动作',exact=True).locator('option[value="carry"]').is_disabled(),'changed anchors cannot blindly carry')
    page.locator('.migration-row[data-mapping="keep"]').click()
    page.get_by_label('迁移动作',exact=True).select_option('carry');page.locator('.migration-record').click()
    page.locator('.migration-prepare').click();expect(page.locator('#feature-notice')).to_contain_text('author and reason')
    check(page.locator('.migration-confirm').count()==0,'preview requires declared author and reason')
    page.get_by_label('编辑者（自述身份）').fill('automated-browser-migration-test');page.get_by_label('本次修改理由').fill('Test-only draft, not user acceptance')
    page.locator('.migration-row[data-mapping="change"]').click();page.get_by_label('迁移动作',exact=True).select_option('replace')
    page.get_by_label('搜索当前实体（需手动选择）').fill('change');page.get_by_role('button',name='change · changed.ts:1',exact=True).click()
    check(page.get_by_label('新实体准确 ID',exact=True).input_value().startswith('node:'),'replacement requires explicit current function selection')
    page.get_by_label('新关联理由',exact=True).fill('Reviewed changed fixture declaration; semantic proposal only')
    page.locator('.migration-record').click();page.locator('.migration-prepare').click()
    expect(page.locator('.migration-confirm')).to_be_visible()
    check('2 条迁入当前快照' in page.locator('#migration-preview').inner_text(),'preview describes selected and deferred records')
    check('4 条失效' in page.locator('#feature-summary').inner_text(),'preview alone does not change document')
    page.screenshot(path=str(root/'preview-migration-evidence.png'),full_page=True)
    page.locator('.migration-confirm').click()
    check('2 条失效' in page.locator('#feature-summary').inner_text(),'confirmation retains deferred stale records')
    check('尚未写入文件' in page.locator('#feature-notice').inner_text(),'confirmation is only an in-memory draft')
    with page.expect_download() as d:page.locator('#feature-export').click()
    dest=root/'migration-edited-test.json';d.value.save_as(dest);exported=json.loads(dest.read_text())
    check(exported['schemaVersion']==2 and exported['history'][-1]['operation']=='migration','export carries versioned migration history')
    check(next(m for m in exported['mappings'] if m['id']=='caller')['basis']['snapshot']!=exported['basis']['snapshot'],'deferred unchanged-ID mapping retains old basis')
    check(all(m['decision']=='proposed' for m in exported['mappings']),'migration never creates acceptance')
    check(json.loads(page.locator('#graph-data').text_content())==initial,'code graph is unchanged')
    page.locator('#feature-import').set_input_files(str(dest));expect(page.locator('#feature-notice')).to_contain_text('已导入')
    check('2 条失效' in page.locator('#feature-summary').inner_text(),'schema 2 import preserves partial migration')
    page.locator('.feature-card').click();page.locator('#feature-mappings .feature-mapping[data-mapping="caller"]').click()
    check(page.locator('.feature-source').count()==0 and page.locator('.feature-review[data-decision="accepted"]').is_disabled(),'deferred records cannot navigate or be accepted')
    page.locator('#feature-mappings .feature-mapping[data-mapping="keep"]').click();page.locator('.feature-correct').click()
    page.get_by_label('修正关联理由',exact=True).fill('Explicit corrected rationale in automated test')
    page.get_by_label('修正代码角色',exact=True).select_option('support');page.locator('.feature-correction-save').click()
    check('Explicit corrected rationale' in page.locator('#detail').inner_text(),'association rationale and role editable via shared API')
    load('migration.html');page.locator('#feature-migrate').click();page.locator('#migration-old-graph').set_input_files(str(root/'migration-old-graph.json'))
    expect(page.locator('.migration-row')).to_have_count(6)
    check('6 条可复用' in page.locator('#migration-summary').inner_text(),'real sample relocation plan without semantic invention')
    page.set_viewport_size({'width':430,'height':900})
    check(page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'),'migration fits narrow viewport')
    check(page.evaluate('globalThis.pwned') is None,'no repository script execution')
    check(not errors,'no browser exceptions');check(not [u for u in requests if not u.startswith('file:')],'no external network requests')
    browser.close()
print(json.dumps({'checks':len(passed),'passed':passed,'browserErrors':errors,'externalRequests':0,'navigation':'set-content' if a.set_content else 'file'}))
