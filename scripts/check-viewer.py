"""Optional real-browser validation. Reports contain data, never executable target code."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser()
parser.add_argument('report')
parser.add_argument('--output', default='preview.png')
parser.add_argument('--legacy-report', help='Schema-compatibility fixture generated by verify-sample.mjs')
parser.add_argument('--chromium')
parser.add_argument('--set-content', action='store_true', help='Use only when the host blocks file:// navigation')
args = parser.parse_args()
checks = []

def check(name, condition):
    assert condition, name
    checks.append(name)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, **({'executable_path': args.chromium} if args.chromium else {}))
    page = browser.new_page(viewport={'width': 1600, 'height': 1100})
    errors, requests = [], []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('request', lambda request: requests.append(request.url))

    def load(report):
        if args.set_content:
            page.set_content(report.read_text(encoding='utf-8'), wait_until='load')
        else:
            page.goto(report.as_uri())
        page.wait_for_selector('.node-row')

    load(Path(args.report).resolve())
    data = json.loads(page.locator('#graph-data').text_content())
    summary = json.loads(page.locator('#resolution-data').text_content())
    revision = data['project'].get('analysisRevision', '未标注（旧报告）')
    check('analysis revision', f'分析规则 {revision}' in page.locator('#revision').inner_text())
    check('map nodes', page.locator('#map .node').count() > 0)
    page.screenshot(path=args.output, full_page=True)
    page.locator('#symbols-tab').click()
    check('symbol navigation', page.locator('.node-row').count() > 0)
    page.locator('.node-row').first.click()
    page.locator('#status').select_option('unresolved')
    check('unresolved status filter', all('未解析' in t for t in page.locator('.edge-row .badge').all_inner_texts()))
    page.locator('#status').select_option('all')
    page.locator('#search').fill('this-query-does-not-exist')
    check('empty search', page.locator('.node-row').count() == 0)
    page.locator('#search').fill('')
    page.locator('#files-tab').click()
    page.locator('.node-row').first.click()
    if page.locator('.edge-row').count():
        page.locator('.edge-row').first.click()
        check('source evidence inspection', '解析依据' in page.locator('#detail').inner_text())
    page.locator('#zoom-in').click()
    check('zoom', page.locator('#map').get_attribute('viewBox') != '0 0 1000 650')
    page.locator('#fit').click()
    check('fit', page.locator('#map').get_attribute('viewBox') == '0 0 1000 650')
    page.locator('#gaps-tab').click()
    check('analysis boundaries', page.locator('.gap').count() > 0)
    check('reason groups from shared summary', page.locator('.reason-group').count() == len(summary['groups']) > 0)
    group = summary['groups'][0]
    page.locator('.reason-group').first.click()
    check('reason details', group['title'] in page.locator('#detail').inner_text())
    check('diagnostic first-page budget', page.locator('.diagnostic-example').count() == min(25, group['count']))
    check('diagnostic first-page evidence', page.locator('.diagnostic-example').first.get_attribute('data-relation') == group['examples'][0])
    diagnostic_image = Path(args.output).with_name(Path(args.output).stem + '-diagnostics.png')
    page.screenshot(path=str(diagnostic_image), full_page=True)
    if page.locator('.diagnostic-next').count():
        first_id = page.locator('.diagnostic-example').first.get_attribute('data-relation')
        page.locator('.diagnostic-next').click()
        check('diagnostic next page', page.locator('.diagnostic-example').first.get_attribute('data-relation') != first_id)
        page.locator('.diagnostic-prev').click()
        check('diagnostic previous page', page.locator('.diagnostic-example').first.get_attribute('data-relation') == first_id)
    chosen_id = page.locator('.diagnostic-example').first.get_attribute('data-relation')
    page.locator('.diagnostic-example').first.click()
    check('diagnostic source drilldown', chosen_id in page.locator('#detail').inner_text() and '未解析分类' in page.locator('#detail').inner_text())
    page.set_viewport_size({'width': 430, 'height': 900})
    check('narrow viewport', page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'))
    check('no repository script execution', page.evaluate('globalThis.pwned') is None)
    if args.legacy_report:
        load(Path(args.legacy_report).resolve())
        check('legacy revision remains unspecified', '分析规则 未标注（旧报告）' in page.locator('#revision').inner_text())
        page.locator('#gaps-tab').click()
        check('legacy reasons remain unclassified', page.locator('.reason-group').count() == 1 and
              page.locator('.reason-group').first.get_attribute('data-reason') == 'unclassified')
        page.locator('.reason-group').first.click()
        check('legacy evidence can still be opened', page.locator('.diagnostic-example').count() > 0)
        page.locator('.diagnostic-example').first.click()
        check('legacy source drilldown', '未分类' in page.locator('#detail').inner_text())
    browser.close()
    check('no browser exceptions', not errors)
    check('no external network requests', not [url for url in requests if not url.startswith('file:')])
    print(json.dumps({'browserErrors': errors, 'networkRequests': 0, 'checks': len(checks), 'passed': checks,
        'navigation': 'set-content' if args.set_content else 'file',
        'skipped': [] if args.legacy_report else ['legacy compatibility: no fixture supplied']}))
