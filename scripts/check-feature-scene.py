"""Presentation-only browser regression. No target program or model is executed."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('directory')
parser.add_argument('--chromium')
parser.add_argument('--set-content', action='store_true')
a = parser.parse_args()
root = Path(a.directory).resolve()
passed, errors, requests = [], [], []
def check(ok, name):
    assert ok, name
    passed.append(name)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, **({'executable_path': a.chromium} if a.chromium else {}))
    page = browser.new_page(viewport={'width': 1680, 'height': 1000}, accept_downloads=True)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: requests.append(r.url))
    page.on('dialog', lambda d: d.accept())
    def load(name):
        html = root / name
        if a.set_content:
            page.set_content(html.read_bytes().decode('utf8'), wait_until='load')
        else:
            page.goto(html.as_uri())
        page.locator('#features-tab').click()
    def reveal(selector):
        el = page.locator(selector)
        panel = el.locator('xpath=ancestor::*[@data-panel]').first
        if panel.count():
            page.locator(f'.feature-detail-tabs [data-tab="{panel.get_attribute("data-panel")}"]').click()
        if el.get_attribute('open') is None:
            el.locator('summary').first.click()
    load('features.html')
    original = page.locator('#feature-data').text_content()
    graph = page.locator('#graph-data').text_content()
    check(page.locator('.feature-card').count() == 2, 'overview contains only explicit features')
    check(page.locator('.feature-card p').count() == 0, 'overview is compact nodes, not long description paragraphs')
    check(page.locator('.feature-membership-line').count() == 0, 'no invented feature-to-feature dependencies')
    first = page.locator('.feature-card[data-feature=window]')
    first.focus(); page.keyboard.press('Enter')
    check(first.get_attribute('aria-pressed') == 'true', 'feature nodes support keyboard selection')
    page.locator('.feature-open-code[data-feature=window]').click()
    check(page.locator('.feature-code-node').count() == 7, 'default shows bounded entry and implementation nodes only')
    check(page.locator('.feature-group-expand[data-role=support]').inner_text().startswith('展开 21'), 'folded support count remains visible')
    check('WindowController.show' in page.locator('.feature-code-node[data-mapping=m0]').inner_text(), 'method label includes lexical class')
    check('WindowController.show · 回调' in page.locator('.feature-code-node[data-mapping=m1]').inner_text(), 'callback label adds context without inventing a function name')
    check('另有 1' in page.locator('.feature-code-node[data-mapping=m0]').inner_text(), 'shared code disclosed without feature arrows')
    check(page.locator('.feature-call-line').count() == 0, 'real-call overlay is opt-in')
    page.screenshot(path=str(root / 'feature-scene.png'), full_page=True)
    page.locator('.feature-group-expand[data-role=support]').click()
    check(page.locator('.feature-code-node[data-role=support]').count() == 5, 'support expands with an explicit budget')
    page.locator('.feature-code-node[data-mapping=m11]').click()
    check('完整关联理由' in page.locator('#detail').inner_text(), 'node selection exposes the original mapping rationale')
    check(page.locator('.feature-review-details').get_attribute('open') is None, 'review controls do not bury reading by default')
    check(page.locator('.feature-identity').get_attribute('open') is None, 'raw IDs and hashes are a separate evidence layer')
    page.locator('.feature-source').click()
    check(page.locator('#local-view').is_visible(), 'code node reuses exact source navigation')
    page.locator('.feature-back').first.click()
    check(page.locator('.feature-code-node[data-role=support]').count() == 5, 'source-return keeps expanded context')
    page.locator('#feature-show-calls').check()
    page.wait_for_timeout(150)
    check(page.locator('.feature-call-line.candidate').count() == 1, 'only the original candidate call is drawn, callback passing excluded')
    reveal('.feature-call-records')
    page.locator('.feature-call-evidence').click()
    page.locator('.feature-evidence').click()
    check('scene:call' in page.locator('#detail').inner_text(), 'call records link back to the original evidence ID')
    page.locator('.feature-back').first.click()
    page.locator('.feature-mode[data-mode=list]').click()
    check(page.locator('.feature-code-node').count() == 25, 'complete-list view has independent pagination')
    page.locator('.feature-list-more').click()
    check(page.locator('.feature-code-node').count() == 34, 'all mappings including tests and rejection remain accessible')
    check(page.locator('.feature-code-node[data-mapping=m10]').get_attribute('data-decision') == 'rejected', 'rejected records remain explicitly marked')
    page.locator('.feature-code-node[data-mapping=m0]').click()
    reveal('.feature-evidence-details')
    page.locator('.feature-evidence').click()
    page.locator('.feature-back').first.click()
    check(page.locator('.feature-code-node').count() == 34, 'evidence-return retains full-list position')
    check(page.locator('#feature-data').text_content() == original, 'navigation does not mutate embedded annotations')
    page.locator('.feature-code-node[data-mapping=m0]').click()
    reveal('.feature-review-details')
    page.get_by_label('编辑者（自述身份）').fill('ui-test')
    page.get_by_label('本次修改理由').fill('Fixture review only')
    page.locator('.feature-review[data-decision=accepted]').click()
    check('人工接受' in page.locator('.feature-code-node[data-mapping=m0]').inner_text(), 'review updates the scene and inspector consistently')
    page.locator('.feature-detail-tabs [data-tab=about]').click()
    check('候选关系' in page.locator('#detail').inner_text(), 'acceptance does not erase candidate status')
    reveal('.feature-document-tools')
    with page.expect_download() as d:
        page.locator('#feature-export').click()
    dest = root / 'edited-test-only.json';d.value.save_as(dest)
    edited = json.loads(dest.read_bytes().decode('utf8'))
    check(edited['mappings'][0]['decision'] == 'accepted', 'manual draft export retains the explicit review')
    page.locator('#feature-import').set_input_files(str(root / 'features.json'))
    expect(page.locator('#feature-notice')).to_contain_text('已载入')
    page.locator('.feature-card[data-feature=window]').click()
    page.locator('.feature-open-code[data-feature=window]').click()
    check('待审' in page.locator('.feature-code-node[data-mapping=m0]').inner_text(), 'import resets the view to the imported sidecar, not an old decision')
    check(page.locator('#graph-data').text_content() == graph, 'navigation and review never mutate the code graph')
    page.locator('#feature-migrate').click()
    check(page.locator('#feature-migration').is_visible() and not page.locator('#feature-mappings').is_visible(), 'migration remains a separate readable workflow')
    page.get_by_role('button', name='返回功能标注', exact=True).click()
    check(page.locator('#feature-mappings').is_visible(), 'closing migration restores the scene')
    page.set_viewport_size({'width': 430, 'height': 900})
    page.wait_for_timeout(150)
    check(page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'long titles and code labels fit a narrow viewport')
    check(page.locator('.feature-call-line').count() == 0, 'narrow code viewport keeps original records without call arrows')
    page.screenshot(path=str(root / 'feature-scene-narrow.png'), full_page=True)
    page.locator('#feature-tree-toggle').click()
    page.locator('#project-tab').click()
    check('feature-active' not in page.locator('body').get_attribute('class'), 'leaving features restores the original layout')
    page.set_viewport_size({'width': 1680, 'height': 1000})
    load('stale.html');page.locator('.feature-open-code[data-feature=window]').click()
    page.locator('.feature-code-node[data-mapping=m0]').click()
    check('已失效' in page.locator('#detail').inner_text(), 'stale state is visible without opening an evidence fold')
    check(page.locator('.feature-source').count() == 0, 'stale records cannot navigate to current same-name source')
    check(page.locator('.feature-review[data-decision=accepted]').is_disabled(), 'stale records cannot be accepted')
    page.locator('#feature-show-calls').check();page.wait_for_timeout(100)
    check(page.locator('.feature-call-evidence').count() == 0, 'stale anchors generate no live code-call edges')
    load('empty.html')
    check(page.locator('.feature-card').count() == 0 and '尚未添加功能' in page.locator('#feature-cards').inner_text(), 'empty input has an honest empty state')
    load('hostile.html')
    check(page.locator('.feature-card img').count() == 0 and page.evaluate('globalThis.featureInjected') is None, 'source-derived titles remain inert text')
    check(not errors, 'no browser exceptions')
    check(not [u for u in requests if not u.startswith(('file:', 'blob:'))], 'no external network requests')
    browser.close()
result = {'checks':len(passed), 'passed':passed, 'browserErrors':errors,
          'navigation':'set-content' if a.set_content else 'file', 'scope':'presentation regression, not semantic evaluation'}
(root / 'scene-checks.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf8')
print(json.dumps(result,ensure_ascii=False))
