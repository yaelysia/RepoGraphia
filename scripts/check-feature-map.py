"""Offline feature-annotation workflow test. Edits affect test drafts, not the sample app."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('directory')
parser.add_argument('--chromium')
parser.add_argument('--set-content', action='store_true')
args = parser.parse_args()
root = Path(args.directory).resolve()
passed, errors, requests = [], [], []

def check(condition, name):
    assert condition, name
    passed.append(name)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, **({'executable_path': args.chromium} if args.chromium else {}))
    page = browser.new_page(viewport={'width': 1650, 'height': 1100}, accept_downloads=True)
    def reveal(selector):
        section = page.locator(selector)
        panel = section.locator('xpath=ancestor::*[@data-panel]').first
        if panel.count():
            page.locator(f'.feature-detail-tabs [data-tab="{panel.get_attribute("data-panel")}"]').click()
        if section.count() and section.get_attribute('open') is None:
            section.locator('summary').first.click()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: requests.append(r.url))
    page.on('dialog', lambda d: d.accept())
    def load(name):
        if args.set_content:
            page.set_content((root / name).read_bytes().decode('utf8'), wait_until='load')
        else:
            page.goto((root / name).as_uri())
    load('features.html')
    original = json.loads(page.locator('#graph-data').text_content())
    page.locator('#features-tab').click()
    check(page.locator('#feature-view').is_visible(), 'feature tab opens independently of directory map')
    check(page.locator('.feature-card').count() == 3, 'three explicitly authored partial features')
    reveal('.feature-document-tools')
    check('6 条映射' in page.locator('#feature-summary').inner_text(), 'six annotations and revision visible')
    check(page.locator('#kind').is_disabled(), 'code-edge filters cannot hide semantic annotations')
    page.screenshot(path=str(root / 'preview-features.png'), full_page=True)
    page.locator('.feature-card[data-feature="source-results"]').click()
    check('待确认' in page.locator('#detail').inner_text(), 'unmapped questions are retained')
    page.locator('.feature-detail-tabs [data-tab="review"]').click()
    check('agent' in page.locator('#detail').inner_text(), 'example origin is agent rather than user-approved')
    page.locator('.feature-open-code[data-feature="source-results"]').click()
    page.locator('.feature-mapping[data-mapping="result-wrapper"]').click()
    check('待审提案' in page.locator('#detail').inner_text(), 'initial mapping has not been self-accepted')
    reveal('.feature-warning-details')
    check('候选关系' in page.locator('#detail').inner_text() and '来源集合不完整' in page.locator('#detail').inner_text(), 'candidate and incomplete provenance survive mapping')
    page.screenshot(path=str(root / 'preview-feature-evidence.png'), full_page=True)
    reveal('.feature-evidence-details')
    page.locator('.feature-evidence').first.click()
    check('bounded-value-origin' in page.locator('#detail').inner_text(), 'mapping opens original relation and value-origin evidence')
    page.locator('.feature-back').first.click()
    page.locator('.feature-mapping[data-mapping="result-wrapper"]').click()
    page.locator('.feature-detail-tabs [data-tab="about"]').click()
    page.locator('.feature-source').click()
    check(page.locator('#local-view').is_visible(), 'feature-to-code reaches existing source explorer')
    check(page.locator('.feature-reverse').count() == 1, 'source reverse mapping uses exact current entity')
    page.locator('.feature-reverse').click()
    reveal('.feature-review-details')
    page.locator('.feature-review[data-decision="accepted"]').click()
    check('invalid actor' in page.locator('#feature-notice').inner_text(), 'review requires explicit author and reason')
    page.get_by_label('编辑者（自述身份）').fill('browser-test-reviewer')
    page.get_by_label('本次修改理由').fill('Test-only decision; not a real product acceptance')
    reveal('.feature-review-details')
    page.locator('.feature-review[data-decision="accepted"]').click()
    reveal('.feature-warning-details')
    candidate_retained='候选关系' in page.locator('#detail').inner_text()
    page.locator('.feature-detail-tabs [data-tab="about"]').click()
    check('人工接受' in page.locator('#detail').inner_text() and candidate_retained, 'acceptance does not promote candidate evidence')
    check('人工接受' in page.locator('.feature-mapping[data-mapping="result-wrapper"]').inner_text(), 'list and inspector update the same review state')
    check('尚未写入文件' in page.locator('#feature-notice').inner_text(), 'in-memory edit is not presented as saved')
    reveal('.feature-document-tools')
    with page.expect_download() as download_info:
        page.locator('#feature-export').click()
    target = root / 'features-edited-test.json'
    download_info.value.save_as(target)
    exported = json.loads(target.read_text())
    check(exported['revision'] == 10 and exported['history'][-1]['actorKind'] == 'manual', 'JSON export preserves revision and declared actor')
    check(json.loads(page.locator('#graph-data').text_content()) == original, 'manual edit does not mutate original graph data')
    # Verify import does not discard a valid draft on malformed input.
    page.locator('#feature-import').set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{"schemaVersion":99}'})
    expect(page.locator('#feature-notice')).to_contain_text('导入失败')
    check('版本 10' in page.locator('#feature-summary').inner_text(), 'invalid import preserves current draft')
    page.locator('#feature-import').set_input_files(str(root / 'features.json'))
    expect(page.locator('#feature-summary')).to_contain_text('版本 9')
    check('版本 9' in page.locator('#feature-summary').inner_text(), 'original sidecar can be reimported without hidden persistence')
    page.locator('.feature-card[data-feature="session-collection"]').click()
    page.locator('.feature-open-code[data-feature="session-collection"]').click()
    page.locator('.feature-mapping[data-mapping="collection-entry"]').click()
    page.locator('.feature-source').click()
    check(page.locator('.feature-reverse').count() == 2, 'shared declaration navigates to two features without inferred dependency')
    page.locator('.feature-reverse').first.click()
    reveal('.feature-review-details')
    page.locator('.feature-review[data-decision="rejected"]').click()
    page.locator('.feature-detail-tabs [data-tab="about"]').click()
    check('已拒绝' in page.locator('#detail').inner_text(), 'explicit rejection remains visible')
    page.locator('#feature-tree-toggle').click()
    page.locator('#project-tab').click()
    check(page.locator('#project-view').is_visible() and page.locator('#kind').is_enabled(), 'returning to project restores original controls')
    # Rename through the same edit API, then create another partial feature in memory.
    page.locator('#features-tab').click()
    page.locator('#feature-breadcrumb button').first.click()
    page.locator('.feature-card[data-feature="session-status"]').click()
    page.locator('.feature-detail-tabs [data-tab="review"]').click()
    page.get_by_role('button', name='编辑功能说明', exact=True).click()
    page.get_by_label('功能名称', exact=True).fill('Status review draft')
    page.locator('.feature-save').click()
    expect(page.locator('.feature-card[data-feature="session-status"]')).to_have_count(1)
    check(page.locator('.feature-card[data-feature="session-status"] strong').inner_text() == 'Status review draft', 'feature meaning can be corrected in the browser')
    page.locator('#feature-new').click()
    page.get_by_label('功能名称', exact=True).fill('Unmapped experiment')
    page.get_by_label('功能说明', exact=True).fill('No automatic code guessing')
    page.locator('.feature-save').click()
    expect(page.locator('.feature-card')).to_have_count(4)
    root_count=page.locator('.feature-card').count()
    page.locator('.feature-card[aria-pressed="true"]').locator('xpath=..').locator('.feature-open-code').click()
    check(root_count == 4 and '尚无代码映射' in page.locator('#feature-mappings').inner_text(), 'new feature stays explicitly unmapped')
    load('features-empty-test.html')
    page.locator('#features-tab').click()
    check(page.locator('.feature-card').count() == 0, 'report without sidecar does not invent or persist features')
    load('features-stale-test.html')
    page.locator('#features-tab').click()
    reveal('.feature-document-tools')
    check('6 条失效' in page.locator('#feature-summary').inner_text(), 'new snapshot invalidates all old mappings explicitly')
    page.locator('.feature-card[data-feature="source-results"]').click()
    page.locator('.feature-open-code[data-feature="source-results"]').click()
    page.locator('.feature-mapping[data-mapping="result-wrapper"]').click()
    check(page.locator('.feature-review[data-decision="accepted"]').is_disabled(), 'stale mapping cannot be accepted')
    check(page.locator('.feature-source').count() == 0 and page.locator('.feature-evidence').count() == 0, 'stale anchors cannot open same-name current code')
    page.set_viewport_size({'width':430,'height':900})
    check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'feature map fits narrow viewport')
    check(page.evaluate('globalThis.pwned') is None, 'no repository-derived script execution')
    browser.close()
check(not errors, 'no feature browser exceptions')
check(not [r for r in requests if not r.startswith('file:')], 'no external network requests')
print(json.dumps({'checks':len(passed),'passed':passed,'browserErrors':errors,'externalRequests':0,'navigation':'set-content' if args.set_content else 'file'}))
