import { randomUUID } from 'node:crypto';
import { AgentError, createAgentApi, digest } from './agent.js';
import { createFeatureMapApi } from './feature-map.js';
import type { Feature, FeatureBasis, FeatureEdit, FeatureMap } from './feature-map.js';
import type { CodeGraph } from './model.js';

const api = createFeatureMapApi();
const clone = <T>(value: T): T => JSON.parse(JSON.stringify(value));
export type FeatureTaskKind = 'overview' | 'feature' | 'changes';
export interface FeatureTask {
  taskVersion: 1; id: string; kind: FeatureTaskKind; goal: string; createdAt: string;
  basis: FeatureBasis; graphDigest: string; featureDigest: string; featureRevision: number;
  allowed: { files: string[]; featureIds: string[]; mappingIds: string[]; newFeatures: boolean; parentId: string | null };
}
export interface FeatureTaskBundle {
  bundleVersion: 1; task: FeatureTask; taskDigest: string; graph: CodeGraph; features: FeatureMap;
  references?: unknown;
}
export interface FeatureRevision {
  revisionProtocol: 1; taskId: string; taskDigest: string; snapshot: string; baseDigest: string; expectedRevision: number;
  batchId: string; summary: string;
  features: { action: 'add' | 'revise'; feature: Feature; reason: string }[];
  mappings: (Omit<Extract<FeatureEdit, { op: 'mapping' }>, 'op'> & { action: 'add' | 'replace'; reason: string })[];
  retractions: { mappingId: string; reason: string }[];
  checks: { featureId: string; nodeId: string; kind: 'support' | 'limit'; quote: string; explanation: string }[];
  exploredFiles: string[]; unexplored: string[];
}
export interface FeatureRevisionChange {
  kind: 'feature' | 'mapping' | 'retraction'; id: string; action: string; reason: string; before: unknown; after: unknown;
}
export interface FeatureRevisionReview {
  document: FeatureMap; changes: FeatureRevisionChange[];
  checks: (FeatureRevision['checks'][number] & { file: string; fileHash: string; start: number; end: number })[];
  exploredFiles: { path: string; hash: string }[]; unexplored: string[];
  summary: { addedFeatures: number; revisedFeatures: number; addedMappings: number; replacedMappings: number; retractions: number; resetMappings: number };
  warnings: string[];
}
function require(ok: unknown, message: string, code = 'INVALID_REVISION'): asserts ok {
  if (!ok) throw new AgentError(code, message, 'Use the frozen task bundle and its proposalHeader. Do not change task versions, scope, decisions or source evidence.');
}
function object(value: unknown, keys: string[], label: string): asserts value is Record<string, unknown> {
  require(value && typeof value === 'object' && !Array.isArray(value) && Object.keys(value).every(k => keys.includes(k)), `Invalid ${label} or unknown field`);
}
function text(value: unknown, label: string, max = 8000): asserts value is string {
  require(typeof value === 'string' && !!value.trim() && value.length <= max, `Invalid ${label}`);
}
function array(value: unknown, label: string, max: number): asserts value is unknown[] {
  require(Array.isArray(value) && value.length <= max, `Invalid ${label} or budget exceeded`);
}
function strings(value: unknown, label: string, max: number): asserts value is string[] {
  array(value, label, max); value.forEach(x => text(x, label, 2000));
  require(new Set(value).size === value.length, `Duplicate ${label}`);
}
const titleKey = (f: Feature) => JSON.stringify([f.parentId ?? null, f.title.trim().toLowerCase()]);

/** Scope is generated by the workspace, then independently enforced by check/apply. */
export function createFeatureTask(graph: CodeGraph, input: unknown, kind: FeatureTaskKind, goal: string,
  allowed: FeatureTask['allowed'], at = new Date().toISOString()): FeatureTaskBundle {
  const features = api.validate(input);
  const task: FeatureTask = { taskVersion: 1, id: randomUUID(), kind, goal, createdAt: at, basis: api.basis(graph),
    graphDigest: digest(graph), featureDigest: digest(features), featureRevision: features.revision, allowed: clone(allowed) };
  return validateFeatureTaskBundle({ bundleVersion: 1, task, taskDigest: digest(task), graph, features });
}

export function validateFeatureTaskBundle(input: unknown): FeatureTaskBundle {
  object(input, ['bundleVersion','task','taskDigest','graph','features','references'], 'task bundle');
  require(input.bundleVersion === 1, 'Unsupported task bundle');
  object(input.task, ['taskVersion','id','kind','goal','createdAt','basis','graphDigest','featureDigest','featureRevision','allowed'], 'task');
  const task = input.task as unknown as FeatureTask, graph = input.graph as CodeGraph, features = api.validate(input.features);
  require(task.taskVersion === 1 && /^[a-f0-9-]{36}$/.test(task.id) && ['overview','feature','changes'].includes(task.kind), 'Invalid task identity or kind');
  text(task.goal, 'task goal', 2000); text(task.createdAt, 'createdAt', 40); require(Number.isFinite(Date.parse(task.createdAt)), 'Invalid task date');
  require(graph?.schemaVersion === 1 && Array.isArray(graph.files) && Array.isArray(graph.nodes) && Array.isArray(graph.relations), 'Invalid task graph');
  require(digest(graph) === task.graphDigest && digest(api.basis(graph)) === digest(task.basis), 'Task graph does not match the frozen input');
  require(digest(features) === task.featureDigest && features.revision === task.featureRevision, 'Task annotations do not match the frozen input');
  require(digest(task) === input.taskDigest, 'Task digest mismatch');
  object(task.allowed, ['files','featureIds','mappingIds','newFeatures','parentId'], 'allowed scope');
  strings(task.allowed.files, 'scope files', 100000); strings(task.allowed.featureIds, 'scope feature IDs', 1000);
  strings(task.allowed.mappingIds, 'scope mapping IDs', 10000);
  require(typeof task.allowed.newFeatures === 'boolean', 'Invalid new-feature permission');
  require(task.allowed.files.every(file => graph.files.some(f => f.path === file)), 'Scope contains an unindexed file');
  require(task.allowed.featureIds.every(id => features.features.some(f => f.id === id)), 'Scope contains an unknown feature');
  require(task.allowed.mappingIds.every(id => features.mappings.some(m => m.id === id && task.allowed.featureIds.includes(m.featureId))), 'Scope contains an unauthorized mapping');
  require(task.allowed.parentId === null || task.allowed.featureIds.includes(task.allowed.parentId), 'Invalid parent scope');
  if (task.kind === 'feature') require(task.allowed.parentId !== null, 'A feature task requires its selected parent');
  return clone({ ...input, features } as unknown as FeatureTaskBundle);
}

export function featureRevisionHeader(bundle: FeatureTaskBundle) {
  const { task } = bundle;
  return { revisionProtocol: 1 as const, taskId: task.id, taskDigest: bundle.taskDigest, snapshot: task.basis.snapshot,
    baseDigest: task.featureDigest, expectedRevision: task.featureRevision };
}

/** Builds a review preview. No persistence, approval or target execution happens here. */
export function checkFeatureRevision(rawBundle: unknown, input: unknown, author: string, at = new Date().toISOString()): FeatureRevisionReview {
  const bundle = validateFeatureTaskBundle(rawBundle), { graph, features: original, task } = bundle;
  const serialized = JSON.stringify(input);
  require(serialized !== undefined && Buffer.byteLength(serialized, 'utf8') <= 5 * 1024 * 1024, 'Revision exceeds 5 MiB');
  object(input, ['revisionProtocol','taskId','taskDigest','snapshot','baseDigest','expectedRevision','batchId','summary','features','mappings','retractions','checks','exploredFiles','unexplored'], 'revision');
  const proposal = input as unknown as FeatureRevision, header = featureRevisionHeader(bundle);
  require(Object.entries(header).every(([key, value]) => input[key] === value), 'Revision belongs to a different task or baseline', 'TASK_CONFLICT');
  text(author, 'declared agent author', 200); text(at, 'date', 40); require(Number.isFinite(Date.parse(at)), 'Invalid date');
  text(proposal.batchId, 'batch ID', 200); require(/^[a-zA-Z0-9][a-zA-Z0-9._:-]*$/.test(proposal.batchId), 'Invalid batch ID');
  text(proposal.summary, 'summary', 2000);
  array(proposal.features, 'features', 20); array(proposal.mappings, 'mappings', 100); array(proposal.retractions, 'retractions', 100);
  array(proposal.checks, 'checks', 200); strings(proposal.exploredFiles, 'explored files', 1000); strings(proposal.unexplored, 'unexplored areas', 100);
  require(proposal.features.length + proposal.mappings.length + proposal.retractions.length + proposal.exploredFiles.length > 0, 'Empty revision');
  const files = new Map(graph.files.map(f => [f.path, f])), nodes = new Map(graph.nodes.map(n => [n.id, n]));
  const beforeFeatures = new Map(original.features.map(f => [f.id, f])), beforeMappings = new Map(original.mappings.map(m => [m.id, m]));
  const featureChanges = new Map<string, FeatureRevision['features'][number]>(), changedMappingIds = new Set<string>();
  const permittedFeatures = new Set(task.allowed.featureIds), permittedMappings = new Set(task.allowed.mappingIds), permittedFiles = new Set(task.allowed.files);
  for (const change of proposal.features) {
    object(change, ['action','feature','reason'], 'feature change'); text(change.reason, 'feature change reason');
    object(change.feature, ['id','title','description','questions','summary','parentId'], 'feature');
    const feature = change.feature;
    require(!featureChanges.has(feature.id), 'Duplicate feature operation');
    require(change.action === 'add' || change.action === 'revise', 'Unknown feature action');
    require(change.action === 'add' ? task.allowed.newFeatures && !beforeFeatures.has(feature.id) : permittedFeatures.has(feature.id) && beforeFeatures.has(feature.id), 'Feature change is outside task scope');
    featureChanges.set(feature.id, change);
  }
  const finalFeatures = [...original.features.filter(f => !featureChanges.has(f.id)), ...proposal.features.map(x => x.feature)];
  const hierarchy = api.hierarchy(finalFeatures);
  for (const { feature } of proposal.features) {
    require(!finalFeatures.some(f => f.id !== feature.id && titleKey(f) === titleKey(feature)), 'Duplicate feature name in the same parent');
    const selectedRoot = task.kind === 'feature' && feature.id === task.allowed.parentId;
    if (selectedRoot) require((feature.parentId ?? null) === (beforeFeatures.get(feature.id)?.parentId ?? null), 'The selected subtree root must retain its original parent');
    if (feature.parentId && !selectedRoot) require(permittedFeatures.has(feature.parentId) || featureChanges.get(feature.parentId)?.action === 'add', 'Parent is outside task scope');
    if (task.kind === 'feature') require(hierarchy.path(feature.id).some(f => f.id === task.allowed.parentId), 'Feature leaves the selected subtree');
  }
  const context = (map: FeatureMap, reason: string) => ({ expectedRevision: map.revision, actor: author, actorKind: 'agent' as const, at, reason });
  let result = clone(original);
  // This new, explicitly reviewed channel can introduce current references while retaining every untouched old basis.
  if (digest(result.basis) !== digest(task.basis) || result.schemaVersion === 1) {
    result.schemaVersion = result.schemaVersion === 3 ? 3 : 2;
    result.mappings = result.mappings.map(m => ({ ...m, basis: clone(m.basis ?? result.basis) }));
    const before = result.basis; result.basis = clone(task.basis); result.revision++;
    result.history.push({ revision: result.revision, actor: author, actorKind: 'agent', at,
      reason: `Revision ${proposal.batchId}: current context; untouched references retain original bases`, operation: 'migration', subject: 'document',
      before: { basis: before }, after: { basis: result.basis, taskId: task.id, retainedOriginalReferences: true } });
  }
  // Validate the complete final forest before applying edits, independent of proposal order.
  result.schemaVersion = 3;
  result.features = clone(finalFeatures);
  api.validate(result);
  const changes: FeatureRevisionChange[] = [];
  for (const change of proposal.features) {
    const old = beforeFeatures.get(change.feature.id);
    const meaning = (f: Feature) => [f.title, f.summary ?? null, f.description, f.parentId ?? null, f.questions];
    if (old && digest(meaning(old)) !== digest(meaning(change.feature)))
      result.mappings = result.mappings.map(m => m.featureId === change.feature.id && m.decision === 'accepted' ? { ...m, decision: 'proposed' } : m);
    result.revision++;
    result.history.push({ revision: result.revision, actor: author, actorKind: 'agent', at, reason: change.reason,
      operation: 'feature', subject: change.feature.id, before: old ?? null, after: clone(change.feature) });
    changes.push({ kind: 'feature', id: change.feature.id, action: change.action, reason: change.reason, before: old ?? null, after: change.feature });
  }
  const touched = new Set(proposal.features.map(change => change.feature.id));
  const query = createAgentApi(graph);
  for (const change of proposal.mappings) {
    object(change, ['action','id','featureId','nodeId','role','rationale','relationIds','reason'], 'mapping change');
    text(change.reason, 'mapping change reason'); require(!changedMappingIds.has(change.id), 'Duplicate mapping operation'); changedMappingIds.add(change.id);
    require(change.action === 'add' || change.action === 'replace', 'Unknown mapping action');
    const previous = beforeMappings.get(change.id);
    require(change.action === 'add' ? !previous : !!previous && permittedMappings.has(change.id) && previous.featureId === change.featureId, 'Mapping change is outside task scope');
    require(permittedFeatures.has(change.featureId) || featureChanges.get(change.featureId)?.action === 'add', 'Mapping feature is outside task scope');
    const node = nodes.get(change.nodeId); require(node && permittedFiles.has(node.location.file), 'Mapping code is outside task scope');
    require(query.inspect(change.nodeId, { sourceLimit: 1 }).source.available, 'Full source is required');
    require(!result.mappings.some(m => {
      if (m.id === change.id || m.featureId !== change.featureId) return false;
      if ((m.basis ?? result.basis).snapshot === task.basis.snapshot) return m.code.nodeId === change.nodeId;
      // Snapshot-local IDs can collide after a same-length rename. Across bases,
      // only the complete original source anchor can identify the same pair.
      return m.code.file === node.location.file && m.code.fileHash === files.get(node.location.file)!.hash &&
        m.code.start === node.location.start && m.code.end === node.location.end && m.code.name === node.name && m.code.kind === node.kind;
    }), 'Duplicate feature/code pair, including rejected records');
    const { action: _, reason, ...fields } = change;
    result = api.edit(graph, result, { op: 'mapping', ...fields }, context(result, reason));
    touched.add(change.featureId);
    changes.push({ kind: 'mapping', id: change.id, action: change.action, reason, before: previous ?? null, after: result.mappings.find(m => m.id === change.id)! });
  }
  for (const change of proposal.retractions) {
    object(change, ['mappingId','reason'], 'retraction'); text(change.reason, 'retraction reason');
    require(permittedMappings.has(change.mappingId) && !changedMappingIds.has(change.mappingId), 'Retraction is outside task scope or duplicated');
    changedMappingIds.add(change.mappingId);
    const previous = beforeMappings.get(change.mappingId)!; require(previous.decision !== 'rejected', 'Mapping is already inactive');
    result = api.edit(graph, result, { op: 'review', id: change.mappingId, decision: 'rejected' }, context(result, `Proposed retraction: ${change.reason}`));
    changes.push({ kind: 'retraction', id: change.mappingId, action: 'retract', reason: change.reason, before: previous,
      after: result.mappings.find(m => m.id === change.mappingId)! });
  }
  // Meaning changes revoke the old acceptance as well. Make that implicit effect reviewable.
  const resetMappings = result.mappings.filter(mapping => !changedMappingIds.has(mapping.id) &&
    beforeMappings.get(mapping.id)?.decision === 'accepted' && mapping.decision === 'proposed');
  for (const mapping of resetMappings) changes.push({ kind: 'mapping', id: mapping.id, action: 'review-reset',
    reason: 'The feature meaning changed; its original acceptance remains in history and this association requires review again.',
    before: beforeMappings.get(mapping.id)!, after: mapping });
  const capturedChecks = proposal.checks.map(check => {
    object(check, ['featureId','nodeId','kind','quote','explanation'], 'check');
    require(touched.has(check.featureId) && ['support','limit'].includes(check.kind), 'Check is unrelated to a changed feature');
    text(check.quote, 'quote', 1200); text(check.explanation, 'check explanation', 4000);
    const node = nodes.get(check.nodeId); require(node && permittedFiles.has(node.location.file), 'Check code is outside task scope');
    const mapping = result.mappings.find(m => m.featureId === check.featureId && m.code.nodeId === check.nodeId && m.decision !== 'rejected' &&
      (m.basis ?? result.basis).snapshot === graph.project.snapshot);
    require(mapping && api.assess(graph, result).mappings.find(m => m.mapping.id === mapping.id)?.current, 'Check must reference a current mapping for the changed feature');
    query.inspect(node.id, { sourceLimit: 1 }); const file = files.get(node.location.file)!;
    require(file.source !== undefined, 'Full source is required for check quotes');
    const body = file.source.slice(node.location.start, node.location.end), offset = body.indexOf(check.quote);
    require(offset >= 0 && body.indexOf(check.quote, offset + 1) < 0, 'Quote is missing or ambiguous in the exact entity');
    return { ...check, file: file.path, fileHash: file.hash, start: node.location.start + offset, end: node.location.start + offset + check.quote.length };
  });
  for (const id of touched) require(['support','limit'].every(kind => capturedChecks.some(check => check.featureId === id && check.kind === kind)), `Feature ${id} needs support and limit checks`);
  require(proposal.exploredFiles.every(file => permittedFiles.has(file)), 'Exploration record is outside task scope');
  return { document: api.validate(result), changes: clone(changes), checks: capturedChecks,
    exploredFiles: proposal.exploredFiles.map(file => ({ path: file, hash: files.get(file)!.hash })), unexplored: [...proposal.unexplored],
    summary: { addedFeatures: proposal.features.filter(c => c.action === 'add').length, revisedFeatures: proposal.features.filter(c => c.action === 'revise').length,
      addedMappings: proposal.mappings.filter(c => c.action === 'add').length, replacedMappings: proposal.mappings.filter(c => c.action === 'replace').length, retractions: proposal.retractions.length, resetMappings: resetMappings.length },
    warnings: ['Source references and quotes are checked; semantic claims and exploration are declared by the Agent, not independently proved.',
      'Applying a revision does not accept its mappings. Untouched decisions retain their original basis; changed associations are proposed.',
      'A retraction preserves the old record and its history as inactive. Its semantic reason still requires human review.'] };
}
